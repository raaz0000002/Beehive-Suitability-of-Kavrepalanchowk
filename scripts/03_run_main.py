#!/usr/bin/env python3
"""Rerun the apiary suitability model from standardised criterion rasters.

One authoritative run: composite score, fixed 1-9 equal-interval classes, class areas,
alternative classifications, a sensitivity ensemble whose scenario count is generated by
the code, per-pixel stability, an exploratory overlay of known apiary locations, and a
manifest that records input hashes and every number the manuscript reports.

Inputs
  --config   weights.json (criterion -> {file, weight, lo, hi}); see weights_literature.json
  --points   optional CSV with columns id,x,y (coordinates in the raster CRS)
  --out      output folder
All rasters must already be standardised to 1-9 (higher = more suitable) on the same grid.
Needs: numpy, scipy, rasterio. RAM: about 10 bytes per cell per criterion.
"""
import argparse, csv, hashlib, json, os, sys, datetime
import numpy as np, rasterio
from scipy.stats import spearmanr

CLASSES = ["Very Low", "Low", "Moderate", "High", "Very High"]
BREAKS = [1.0, 2.6, 4.2, 5.8, 7.4, 9.0]          # five 1.6-wide classes on the 1-9 scale
OAT = [-0.30, -0.20, -0.10, 0.10, 0.20, 0.30]


def sha256(path):
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for b in iter(lambda: f.read(1 << 20), b""):
            h.update(b)
    return h.hexdigest()


def classify(score, breaks):
    c = np.digitize(score, breaks[1:-1], right=True)   # 0..4; upper bound inclusive
    return c.astype(np.int8)


def norm(w):
    s = sum(w.values())
    return {k: v / s for k, v in w.items()}


def oat(base, k, d):
    """Change criterion k by fraction d; rescale the others so the total stays 1."""
    nk = base[k] * (1 + d)
    rest = 1 - base[k]
    return {j: (nk if j == k else base[j] * (1 - nk) / rest) for j in base}


def roc(base):
    order = sorted(base, key=lambda k: -base[k])
    n = len(order)
    return {k: sum(1 / j for j in range(i, n + 1)) / n for i, k in enumerate(order, 1)}


def wkappa(a, b, k=5):
    """Quadratic-weighted Cohen's kappa between two class arrays (0..k-1)."""
    cm = np.bincount(a * k + b, minlength=k * k).reshape(k, k).astype(float)
    n = cm.sum()
    if n == 0:
        return 1.0
    i, j = np.indices((k, k))
    W = (i - j) ** 2 / (k - 1) ** 2
    E = np.outer(cm.sum(1), cm.sum(0)) / n
    denom = (W * E).sum()
    if denom == 0:
        return 1.0 if np.array_equal(a, b) else 0.0
    return 1 - (W * cm).sum() / denom


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--config", required=True)
    ap.add_argument("--points")
    ap.add_argument("--out", required=True)
    ap.add_argument("--sample", type=int, default=200000, help="pixels sampled for Spearman r")
    a = ap.parse_args()
    os.makedirs(a.out, exist_ok=True)
    with open(a.config, "r", encoding="utf-8") as f:
        cfg = json.load(f)
    root = os.path.dirname(os.path.abspath(a.config))
    crit = cfg["criteria"]
    extra = cfg.get("scenario_layers", {})        # optional layers used only in scenarios (e.g. NDVI, air temperature)
    files = {k: os.path.join(root, v["file"]) for k, v in crit.items()}
    files.update({k: os.path.join(root, v["file"]) for k, v in extra.items()})

    # ---- load on one grid, one common mask for every scenario
    data, prof = {}, None
    for k, f in files.items():
        with rasterio.open(f) as r:
            arr = r.read(1, masked=True).astype("float64")
            if prof is None:
                prof, shape, tr, crs = r.profile, r.shape, r.transform, r.crs
            elif r.shape != shape or r.transform != tr or r.crs != crs:
                sys.exit(f"{f}: grid differs from the first raster (shape, transform or CRS)")
            data[k] = np.ma.masked_equal(arr, 0)     # 0 = NoData/background, as in the original workflow
    mask = np.ones(shape, bool)
    for k, arr in data.items():
        mask &= ~np.ma.getmaskarray(arr)
    for k, arr in data.items():
        v = arr.data[mask]
        if v.min() < 1 - 1e-6 or v.max() > 9 + 1e-6:
            sys.exit(f"{k}: values outside 1-9 ({v.min()}..{v.max()}); standardise first")
        data[k] = v                                  # 1-D vectors of valid cells
    n = int(mask.sum())
    if crs is not None and crs.is_geographic:
        sys.exit("Raster CRS is geographic; reproject to a metric CRS so areas are correct")
    cell_km2 = abs(tr.a * tr.e) / 1e6
    area = n * cell_km2

    base = norm({k: v["weight"] for k, v in crit.items()})

    def score(w):
        s = np.zeros(n, "float64")
        for k, v in w.items():
            if v:
                s += float(v) * data[k]
        return s

    S0 = score(base); C0 = classify(S0, BREAKS)

    # ---- scenarios (the list itself defines the count reported in the paper)
    sc = [("Baseline (literature weights)", base)]
    for k in base:
        for d in OAT:
            sc.append((f"{k} {d:+.0%}", oat(base, k, d)))
    for k in base:
        sc.append((f"Remove {k}", norm({j: (0 if j == k else base[j]) for j in base})))
    for k, v in crit.items():
        for bound in ("lo", "hi"):
            if bound in v:
                tgt = v[bound]; rest = 1 - base[k]
                sc.append((f"{k} at 90% {bound} ({tgt:.3f})", {j: (tgt if j == k else base[j] * (1 - tgt) / rest) for j in base}))
    sc.append(("Equal weights", norm({k: 1 for k in base})))
    sc.append(("Rank-order centroid (ROC)", roc(base)))
    for name, spec in cfg.get("extra_scenarios", {}).items():
        sc.append((name, norm(spec)))
    for name, spec in cfg.get("swap_scenarios", {}).items():   # e.g. use air temperature in place of LST
        w = dict(base); w[spec["use"]] = w.pop(spec["replace"]); sc.append((name, w))

    rng = np.random.default_rng(42)
    samp = rng.choice(n, min(a.sample, n), replace=False)
    hv0 = np.isin(C0, [3, 4]).mean() * 100
    rows, sum_s, sum_s2, same = [], np.zeros(n, "float64"), np.zeros(n, "float64"), np.zeros(n, "int32")
    for name, w in sc:
        S = S0 if name.startswith("Baseline") else score(w)
        C = classify(S, BREAKS)
        sum_s += S; sum_s2 += S.astype("float64") ** 2; same += (C == C0)
        ch = (C != C0).mean()
        rows.append(dict(scenario=name, weights=json.dumps({k: round(v, 4) for k, v in w.items() if v}),
                         spearman_r=round(spearmanr(S0[samp], S[samp])[0], 4),
                         agreement_pct=round(100 * (1 - ch), 2), weighted_kappa=round(wkappa(C0, C), 3),
                         changed_km2=round(ch * area, 2), changed_pct=round(100 * ch, 2),
                         high_plus_very_high_pct=round(np.isin(C, [3, 4]).mean() * 100, 2)))
    N = len(sc)
    with open(os.path.join(a.out, "scenarios.csv"), "w", newline="", encoding="utf-8") as f:
        wr = csv.DictWriter(f, rows[0].keys())
        wr.writeheader()
        wr.writerows(rows)

    # ---- class areas and alternative classifications
    def shares(C):
        cnt = np.bincount(C, minlength=5)
        return [(CLASSES[i], int(cnt[i]), round(cnt[i] * cell_km2, 2), round(100 * cnt[i] / n, 2)) for i in range(5)]
    with open(os.path.join(a.out, "class_areas.csv"), "w", newline="", encoding="utf-8") as f:
        wr = csv.writer(f)
        wr.writerow(["class", "score_range", "pixels", "area_km2", "area_pct"])
        for i, (c, p, km, pc) in enumerate(shares(C0)):
            wr.writerow([c, f"{BREAKS[i]}-{BREAKS[i+1]}", p, km, pc])
    lo_, hi_ = float(S0.min()), float(S0.max())
    alt = {"Fixed 1-9 equal interval (main)": BREAKS,
           "Observed-range equal interval": list(np.linspace(lo_, hi_, 6)),
           "Quantile (quintiles)": [lo_] + list(np.quantile(S0, [0.2, 0.4, 0.6, 0.8])) + [hi_]}
    with open(os.path.join(a.out, "classification_methods.csv"), "w", newline="", encoding="utf-8") as f:
        wr = csv.writer(f)
        wr.writerow(["method", "breaks", "high_plus_very_high_pct", "agreement_with_main_pct", "weighted_kappa"])
        for m, b in alt.items():
            C = classify(S0, b)
            wr.writerow([m, " / ".join(f"{x:.4f}" for x in b), round(np.isin(C, [3, 4]).mean() * 100, 2),
                         round(100 * (C == C0).mean(), 2), round(wkappa(C0, C), 3)])

    # ---- rasters
    def put(vec, fill, dtype):
        out = np.full(shape, fill, dtype)
        out[mask] = vec
        return out
    p = prof.copy()
    p.update(count=1, compress="deflate")
    sd = np.sqrt(np.maximum(sum_s2 / N - (sum_s / N) ** 2, 0)).astype("float32")
    for nm, vec, dt, nd in [("score.tif", S0, "float64", -9999), ("class.tif", (C0 + 1), "int8", 0),
                            ("stability_pct.tif", (100 * same / N).astype("float32"), "float32", -9999),
                            ("score_sd.tif", sd, "float32", -9999)]:
        p.update(dtype=dt, nodata=nd)
        with rasterio.open(os.path.join(a.out, nm), "w", **p) as w:
            w.write(put(vec, nd, dt), 1)

    # ---- known apiary locations (exploratory comparison, not validation)
    pts_summary = None
    if a.points:
        full = put(S0, np.nan, "float64")
        rowsP = []
        with open(a.points, "r", encoding="utf-8") as f:
            for r in csv.DictReader(f):
                rr, cc = rasterio.transform.rowcol(tr, float(r["x"]), float(r["y"]))
                ok = 0 <= rr < shape[0] and 0 <= cc < shape[1] and mask[rr, cc]
                s = float(full[rr, cc]) if ok else None
                rowsP.append(dict(id=r["id"], x=r["x"], y=r["y"], score=None if s is None else round(s, 4),
                                  cls=None if s is None else CLASSES[int(classify(np.array([s]), BREAKS)[0])],
                                  landscape_percentile=None if s is None else round(100 * (S0 < s).mean(), 1)))
        with open(os.path.join(a.out, "points.csv"), "w", newline="", encoding="utf-8") as f:
            wr = csv.DictWriter(f, rowsP[0].keys())
            wr.writeheader()
            wr.writerows(rowsP)
        v = [r for r in rowsP if r["score"] is not None]
        k = sum(r["cls"] in ("High", "Very High") for r in v)
        pts_summary = dict(n_inside=len(v), n_outside=len(rowsP) - len(v), in_high_or_very_high=k,
                           share_pct=round(100 * k / len(v), 1) if v else None, landscape_share_pct=round(hv0, 2),
                           median_landscape_percentile=float(np.median([r["landscape_percentile"] for r in v])) if v else None)

    man = dict(run_utc=datetime.datetime.now(datetime.timezone.utc).isoformat(timespec="seconds"),
               python=sys.version.split()[0], numpy=np.__version__, rasterio=rasterio.__version__,
               inputs={k: dict(file=os.path.relpath(f, root), sha256=sha256(f)) for k, f in files.items()},
               weights={k: round(v, 6) for k, v in base.items()}, breaks=BREAKS,
               cells=n, cell_km2=cell_km2, area_km2=round(area, 3),
               score=dict(min=round(lo_, 4), max=round(hi_, 4), mean=round(float(S0.mean()), 4), sd=round(float(S0.std()), 4)),
               class_areas=shares(C0), high_plus_very_high_pct=round(hv0, 2),
               scenario_count=N, points=pts_summary)
    with open(os.path.join(a.out, "manifest.json"), "w", encoding="utf-8") as f:
        json.dump(man, f, indent=2)
    print(f"cells {n}  area {area:.3f} km2  score {lo_:.4f}-{hi_:.4f}  H+VH {hv0:.2f}%  scenarios {N}")
    if pts_summary:
        print("points", pts_summary)


if __name__ == "__main__":
    main()
